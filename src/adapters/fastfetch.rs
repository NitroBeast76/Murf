// Fastfetch adapter.
//
// Writes a full fastfetch config with Murf colors. Since fastfetch's
// --config replaces the entire config, the module list must be
// explicit. Edit MODULES below to change what the theme shows.

use super::{home_dir, AppAdapter, ReloadOutcome, WriteOp};
use crate::palette::Palette;
use anyhow::Result;
use std::path::PathBuf;

pub struct Fastfetch;

/// Modules shown by the Murf fastfetch theme, in order. Edit this
/// list to add, remove, or reorder rows.
const MODULES: &[&str] = &[
    "title",
    "separator",
    "os",
    "host",
    "kernel",
    "uptime",
    "packages",
    "shell",
    "display",
    "de",
    "wm",
    "wmtheme",
    "theme",
    "icons",
    "font",
    "cursor",
    "terminal",
    "terminalfont",
    "cpu",
    "gpu",
    "memory",
    "swap",
    "disk",
    "localip",
    "battery",
    "poweradapter",
    "locale",
    "break",
    "colors",
];

impl Fastfetch {
    fn theme_path() -> Option<PathBuf> {
        Some(
            home_dir()?
                .join(".config")
                .join("fastfetch")
                .join("murf.jsonc"),
        )
    }
}

impl AppAdapter for Fastfetch {
    fn id(&self) -> &'static str { "fastfetch" }
    fn display_name(&self) -> &'static str { "Fastfetch" }

    fn detect(&self) -> Vec<PathBuf> {
        match Self::theme_path() {
            Some(p) => vec![p],
            None => vec![],
        }
    }

    fn plan(&self, palette: &Palette) -> Result<Vec<WriteOp>> {
        let Some(path) = Self::theme_path() else { return Ok(vec![]); };

        // Logo colors 1..9 map to fastfetch's logo slot names.
        // Map them to distinct M3 roles so the ASCII logo has variety.
        let l1 = palette.hex_or("primary",             "#ffffff");
        let l2 = palette.hex_or("secondary",           "#cccccc");
        let l3 = palette.hex_or("tertiary",            "#aaaaaa");
        let l4 = palette.hex_or("primary_container",   "#888888");
        let l5 = palette.hex_or("secondary_container", "#777777");
        let l6 = palette.hex_or("tertiary_container",  "#666666");
        let l7 = palette.hex_or("on_surface",          "#ffffff");
        let l8 = palette.hex_or("outline",             "#888888");
        let l9 = palette.hex_or("error",               "#ff0000");

        let keys   = palette.hex_or("primary",    "#ffffff");
        let title  = palette.hex_or("primary",    "#ffffff");
        let output = palette.hex_or("on_surface", "#ffffff");
        let main   = palette.hex_or("on_surface", "#ffffff");

        // Build the modules array as JSON.
        let modules_json: String = MODULES
            .iter()
            .map(|m| format!("    \"{}\"", m))
            .collect::<Vec<_>>()
            .join(",\n");

        let content = format!(
            "// Generated by Murf. Do not edit; changes will be overwritten.\n\
             // Run: fastfetch --config \"{path}\"\n\
             {{\n\
             \x20 \"logo\": {{\n\
             \x20   \"padding\": {{ \"top\": 1, \"left\": 2 }},\n\
             \x20   \"color\": {{\n\
             \x20     \"1\": \"{l1}\",\n\
             \x20     \"2\": \"{l2}\",\n\
             \x20     \"3\": \"{l3}\",\n\
             \x20     \"4\": \"{l4}\",\n\
             \x20     \"5\": \"{l5}\",\n\
             \x20     \"6\": \"{l6}\",\n\
             \x20     \"7\": \"{l7}\",\n\
             \x20     \"8\": \"{l8}\",\n\
             \x20     \"9\": \"{l9}\"\n\
             \x20   }}\n\
             \x20 }},\n\
             \x20 \"display\": {{\n\
             \x20   \"separator\": \" \",\n\
             \x20   \"color\": {{\n\
             \x20     \"keys\":   \"{keys}\",\n\
             \x20     \"title\":  \"{title}\",\n\
             \x20     \"output\": \"{output}\",\n\
             \x20     \"main\":   \"{main}\"\n\
             \x20   }}\n\
             \x20 }},\n\
             \x20 \"modules\": [\n\
             {modules}\n\
             \x20 ]\n\
             }}\n",
            path = path.display(),
            l1 = l1, l2 = l2, l3 = l3, l4 = l4, l5 = l5,
            l6 = l6, l7 = l7, l8 = l8, l9 = l9,
            keys = keys,
            title = title,
            output = output,
            main = main,
            modules = modules_json,
        );

        Ok(vec![WriteOp::File {
            adapter: "fastfetch",
            target: path,
            content,
        }])
    }

    fn reload(&self) -> Result<ReloadOutcome> {
        Ok(ReloadOutcome { deferred: 1, ..Default::default() })
    }
}
