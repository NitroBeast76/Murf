// Fastfetch adapter.
//
// Writes a complete, standalone config with a standard module set
// and Murf colors. The user points their profile at this file.
//
// To change which modules are shown, edit the MODULES array below.

use super::{home_dir, AppAdapter, ReloadOutcome, WriteOp};
use crate::palette::Palette;
use anyhow::Result;
use std::path::PathBuf;

pub struct Fastfetch;

impl Fastfetch {
    fn config_path() -> Option<PathBuf> {
        Some(home_dir()?.join(".config").join("fastfetch").join("murf.jsonc"))
    }
}

impl AppAdapter for Fastfetch {
    fn id(&self) -> &'static str { "fastfetch" }
    fn display_name(&self) -> &'static str { "Fastfetch" }

    fn detect(&self) -> Vec<PathBuf> {
        let dir = match home_dir() {
            Some(h) => h.join(".config").join("fastfetch"),
            None => return vec![],
        };
        if !dir.exists() { return vec![]; }
        Self::config_path().into_iter().collect()
    }

    fn plan(&self, palette: &Palette) -> Result<Vec<WriteOp>> {
        let Some(path) = Self::config_path() else { return Ok(vec![]); };

        let l1 = palette.hex_or("primary",             "#ffffff");
        let l2 = palette.hex_or("secondary",           "#cccccc");
        let l3 = palette.hex_or("tertiary",            "#aaaaaa");
        let l4 = palette.hex_or("primary_container",   "#888888");
        let l5 = palette.hex_or("secondary_container", "#777777");
        let l6 = palette.hex_or("tertiary_container",  "#666666");
        let l7 = palette.hex_or("on_surface",          "#ffffff");
        let l8 = palette.hex_or("outline",             "#888888");
        let l9 = palette.hex_or("error",               "#ff0000");

        let keys      = palette.hex_or("primary",    "#ffffff");
        let title     = palette.hex_or("primary",    "#ffffff");
        let output    = palette.hex_or("on_surface", "#ffffff");
        let separator = palette.hex_or("outline",    "#888888");

        let content = format!(
            "// Generated by Murf. Do not edit; changes will be overwritten.\n\
             {{\n\
             \x20 \"logo\": {{\n\
             \x20   \"type\": \"windows\",\n\
             \x20   \"padding\": {{ \"top\": 1, \"left\": 2, \"right\": 4 }},\n\
             \x20   \"color\": {{\n\
             \x20     \"1\": \"{l1}\",\n\
             \x20     \"2\": \"{l2}\",\n\
             \x20     \"3\": \"{l3}\",\n\
             \x20     \"4\": \"{l4}\",\n\
             \x20     \"5\": \"{l5}\",\n\
             \x20     \"6\": \"{l6}\",\n\
             \x20     \"7\": \"{l7}\",\n\
             \x20     \"8\": \"{l8}\",\n\
             \x20     \"9\": \"{l9}\"\n\
             \x20   }}\n\
             \x20 }},\n\
             \x20 \"display\": {{\n\
             \x20   \"separator\": \" \",\n\
             \x20   \"color\": {{\n\
             \x20     \"keys\":      \"{keys}\",\n\
             \x20     \"title\":     \"{title}\",\n\
             \x20     \"output\":    \"{output}\",\n\
             \x20     \"separator\": \"{separator}\"\n\
             \x20   }}\n\
             \x20 }},\n\
             \x20 \"modules\": [\n\
             \x20   \"title\",\n\
             \x20   \"separator\",\n\
             \x20   \"os\",\n\
             \x20   \"host\",\n\
             \x20   \"kernel\",\n\
             \x20   \"uptime\",\n\
             \x20   \"packages\",\n\
             \x20   \"shell\",\n\
             \x20   \"display\",\n\
             \x20   \"de\",\n\
             \x20   \"wm\",\n\
             \x20   \"theme\",\n\
             \x20   \"cpu\",\n\
             \x20   \"gpu\",\n\
             \x20   \"memory\",\n\
             \x20   \"disk\",\n\
             \x20   \"localip\",\n\
             \x20   \"break\",\n\
             \x20   \"colors\"\n\
             \x20 ]\n\
             }}\n",
            l1 = l1, l2 = l2, l3 = l3, l4 = l4, l5 = l5,
            l6 = l6, l7 = l7, l8 = l8, l9 = l9,
            keys = keys, title = title, output = output, separator = separator,
        );

        Ok(vec![WriteOp::File {
            adapter: "fastfetch",
            target: path,
            content,
        }])
    }

    fn reload(&self) -> Result<ReloadOutcome> {
        Ok(ReloadOutcome { deferred: 1, ..Default::default() })
    }
}
