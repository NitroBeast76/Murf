// Fastfetch adapter.
//
// Writes a minimal JSONC config that themes fastfetch's colors. The
// user runs `fastfetch --config <path>` (or an alias in their shell
// profile) to use it.
//
// The config only sets logo colors and display colors. Fastfetch
// fills in everything else with its defaults.

use super::{home_dir, AppAdapter, ReloadOutcome, WriteOp};
use crate::palette::Palette;
use anyhow::Result;
use std::path::PathBuf;

pub struct Fastfetch;

impl Fastfetch {
    fn theme_path() -> Option<PathBuf> {
        Some(home_dir()?.join(".config").join("fastfetch").join("murf.jsonc"))
    }
}

impl AppAdapter for Fastfetch {
    fn id(&self) -> &'static str { "fastfetch" }
    fn display_name(&self) -> &'static str { "Fastfetch" }

    fn detect(&self) -> Vec<PathBuf> {
        // Always available. The user opts in by pointing --config at
        // the theme path.
        match Self::theme_path() {
            Some(p) => vec![p],
            None => vec![],
        }
    }

    fn plan(&self, palette: &Palette) -> Result<Vec<WriteOp>> {
        let Some(path) = Self::theme_path() else { return Ok(vec![]); };

        // Logo colors 1..9 map to fastfetch's slot names. We map them
        // to distinct M3 roles so the ASCII logo has visible variety.
        let logo_1 = palette.hex_or("primary",             "#ffffff");
        let logo_2 = palette.hex_or("secondary",           "#cccccc");
        let logo_3 = palette.hex_or("tertiary",            "#aaaaaa");
        let logo_4 = palette.hex_or("primary_container",   "#888888");
        let logo_5 = palette.hex_or("secondary_container", "#777777");
        let logo_6 = palette.hex_or("tertiary_container",  "#666666");
        let logo_7 = palette.hex_or("on_surface",          "#ffffff");
        let logo_8 = palette.hex_or("outline",             "#888888");
        let logo_9 = palette.hex_or("error",               "#ff0000");

        let keys   = palette.hex_or("primary",             "#ffffff");
        let title  = palette.hex_or("primary",             "#ffffff");
        let output = palette.hex_or("on_surface",          "#ffffff");
        let main   = palette.hex_or("on_surface",          "#ffffff");

        let content = format!(
            "// Generated by Murf. Do not edit; changes will be overwritten.\n\
             // Run: fastfetch --config \"{path}\"\n\
             {{\n\
             \x20 \"logo\": {{\n\
             \x20   \"type\": \"small\",\n\
             \x20   \"padding\": {{ \"top\": 1, \"left\": 2 }},\n\
             \x20   \"color\": {{\n\
             \x20     \"1\": \"{l1}\",\n\
             \x20     \"2\": \"{l2}\",\n\
             \x20     \"3\": \"{l3}\",\n\
             \x20     \"4\": \"{l4}\",\n\
             \x20     \"5\": \"{l5}\",\n\
             \x20     \"6\": \"{l6}\",\n\
             \x20     \"7\": \"{l7}\",\n\
             \x20     \"8\": \"{l8}\",\n\
             \x20     \"9\": \"{l9}\"\n\
             \x20   }}\n\
             \x20 }},\n\
             \x20 \"display\": {{\n\
             \x20   \"separator\": \" \",\n\
             \x20   \"color\": {{\n\
             \x20     \"keys\":   \"{keys}\",\n\
             \x20     \"title\":  \"{title}\",\n\
             \x20     \"output\": \"{output}\",\n\
             \x20     \"main\":   \"{main}\"\n\
             \x20   }}\n\
             \x20 }}\n\
             }}\n",
            path = path.display(),
            l1 = logo_1,
            l2 = logo_2,
            l3 = logo_3,
            l4 = logo_4,
            l5 = logo_5,
            l6 = logo_6,
            l7 = logo_7,
            l8 = logo_8,
            l9 = logo_9,
            keys = keys,
            title = title,
            output = output,
            main = main,
        );

        Ok(vec![WriteOp::File {
            adapter: "fastfetch",
            target: path,
            content,
        }])
    }

    fn reload(&self) -> Result<ReloadOutcome> {
        // fastfetch runs per invocation; nothing to reload.
        Ok(ReloadOutcome { deferred: 1, ..Default::default() })
    }
}
