// YASB adapter.

use super::{home_dir, inject_at_top, AppAdapter, ReloadOutcome, WriteOp};
use crate::palette::Palette;
use anyhow::{Context, Result};
use std::fs;
use std::path::PathBuf;
use std::process::Command;

pub struct Yasb;

const MARKER_OPEN: &str = "/* <murf> */";
const MARKER_CLOSE: &str = "/* </murf> */";
const COLORS_FILE: &str = "murf-colors.css";

impl Yasb {
    fn config_dir() -> Option<PathBuf> {
        let p = home_dir()?.join(".config").join("yasb");
        if p.exists() { Some(p) } else { None }
    }
    fn styles_path() -> Option<PathBuf> {
        Some(Self::config_dir()?.join("styles.css"))
    }
    fn colors_path() -> Option<PathBuf> {
        Some(Self::config_dir()?.join(COLORS_FILE))
    }
}

impl AppAdapter for Yasb {
    fn id(&self) -> &'static str { "yasb" }
    fn display_name(&self) -> &'static str { "YASB" }

    fn detect(&self) -> Vec<PathBuf> {
        match Self::styles_path() {
            Some(p) if p.exists() => vec![p],
            _ => vec![],
        }
    }

    fn plan(&self, palette: &Palette) -> Result<Vec<WriteOp>> {
        let Some(styles) = Self::styles_path() else { return Ok(vec![]) };
        let Some(colors) = Self::colors_path() else { return Ok(vec![]) };
        if !styles.exists() { return Ok(vec![]); }

        let mut css = String::from(
            "/* Generated by Murf. Do not edit; changes will be overwritten. */\n\
             :root {\n",
        );
        for (name, role) in [
            ("bg",           "surface"),
            ("fg",           "on_surface"),
            ("primary",      "primary"),
            ("on-primary",   "on_primary"),
            ("secondary",    "secondary"),
            ("tertiary",     "tertiary"),
            ("error",        "error"),
            ("outline",      "outline"),
            ("surface-dim",  "surface_dim"),
            ("surface-high", "surface_container_high"),
        ] {
            css.push_str(&format!(
                "  --murf-{}: {};\n",
                name,
                palette.hex_or(role, "#000000")
            ));
        }
        css.push_str("}\n");

        let mut ops = vec![WriteOp::File {
            adapter: "yasb",
            target: colors,
            content: css,
        }];

        let styles_text = fs::read_to_string(&styles)
            .with_context(|| format!("reading {}", styles.display()))?;

        let has_import = styles_text.lines().any(|l| {
            let t = l.trim();
            t.contains(COLORS_FILE) && t.starts_with("@import")
        });

        if !has_import {
            let new_text = inject_at_top(
                &styles_text,
                MARKER_OPEN,
                MARKER_CLOSE,
                &format!("@import \"{}\";", COLORS_FILE),
            );
            ops.push(WriteOp::File {
                adapter: "yasb",
                target: styles,
                content: new_text,
            });
        }

        Ok(ops)
    }

    fn reload(&self) -> Result<ReloadOutcome> {
        // YASB has no reliable live reload. Kill and relaunch.
        let _ = Command::new("taskkill")
            .args(["/IM", "yasb.exe", "/F"])
            .output();
        std::thread::sleep(std::time::Duration::from_millis(400));

        for bin in ["yasb.exe", "yasb"] {
            match Command::new("cmd")
                .args(["/C", "start", "", bin])
                .spawn()
            {
                Ok(_) => {
                    tracing::info!(binary = bin, "yasb restarted");
                    return Ok(ReloadOutcome { restarted: 1, ..Default::default() });
                }
                Err(_) => continue,
            }
        }

        tracing::warn!("could not relaunch yasb; check PATH");
        Ok(ReloadOutcome { deferred: 1, ..Default::default() })
    }
}
