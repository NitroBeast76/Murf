// YASB adapter.

use super::{home_dir, inject_at_top, AppAdapter, ReloadOutcome, WriteOp};
use crate::palette::Palette;
use anyhow::{Context, Result};
use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::os::windows::process::CommandExt;

pub struct Yasb;

const MARKER_OPEN: &str = "/* <murf> */";
const MARKER_CLOSE: &str = "/* </murf> */";
const COLORS_FILE: &str = "murf-colors.css";

impl Yasb {
    fn config_dir() -> Option<PathBuf> {
        let p = home_dir()?.join(".config").join("yasb");
        if p.exists() { Some(p) } else { None }
    }
    
    // Made public for the CLI commands in main.rs
    pub fn styles_path() -> Option<PathBuf> {
        Some(Self::config_dir()?.join("styles.css"))
    }

    fn yasb_config_path() -> Option<PathBuf> {
        Some(Self::config_dir()?.join("config.yaml"))
    }

    fn watching_stylesheet() -> bool {
        let Some(path) = Self::yasb_config_path() else { return true };
        let Ok(text) = fs::read_to_string(&path) else { return true };
        for line in text.lines() {
            let t = line.trim();
            let rest = if let Some(r) = t.strip_prefix("watch_stylesheet:") {
                r
            } else if let Some(r) = t.strip_prefix("watch_stylesheets:") {
                r
            } else { continue };
            return !rest.trim().trim_end_matches(',').eq_ignore_ascii_case("false");
        }
        true
    }
}

impl AppAdapter for Yasb {
    fn id(&self) -> &'static str { "yasb" }
    fn display_name(&self) -> &'static str { "YASB" }

    fn detect(&self, cfg: &crate::config::AppCfg) -> Vec<PathBuf> {
        if let Some(dir) = &cfg.config_dir {
            let p = PathBuf::from(dir).join("styles.css");
            if p.exists() { return vec![p]; }
        }
        match Self::styles_path() {
            Some(p) if p.exists() => vec![p],
            _ => vec![],
        }
    }

    fn plan(&self, palette: &Palette, cfg: &crate::config::AppCfg) -> Result<Vec<WriteOp>> {
        let Some(styles) = self.detect(cfg).into_iter().next() else { return Ok(vec![]); };

        let styles_text = fs::read_to_string(&styles)
            .with_context(|| format!("reading {}", styles.display()))?;

        if cfg.auto_theme {
            // --- NEW AUTO-THEME MODE (v0.2.2) ---
            let stripped = super::yasb_auto::strip_block(&styles_text);
            let block = super::yasb_auto::generate_override_block(palette);
            let new_text = format!("{}{}", stripped, block);
            
            Ok(vec![WriteOp::File {
                adapter: "yasb",
                target: styles,
                content: new_text,
                atomic: false,
            }])
        } else {
            // --- LEGACY COMPANION FILE MODE (v0.2.1) ---
            let Some(colors) = styles.parent().map(|p| p.join(COLORS_FILE)) else { return Ok(vec![]); };
            
            let mut css = String::from("/* Generated by Murf. Do not edit; changes will be overwritten. */\n:root {\n");
            for (name, role) in [
                ("bg",           "surface"),
                ("fg",           "on_surface"),
                ("primary",      "primary"),
                ("on-primary",   "on_primary"),
                ("secondary",    "secondary"),
                ("tertiary",     "tertiary"),
                ("error",        "error"),
                ("outline",      "outline"),
                ("surface-dim",  "surface_dim"),
                ("surface-high", "surface_container_high"),
            ] {
                css.push_str(&format!("  --murf-{}: {};\n", name, palette.hex_or(role, "#000000")));
            }
            css.push_str("}\n");

            let mut ops = vec![WriteOp::File {
                adapter: "yasb", target: colors, content: css, atomic: false,
            }];

            let has_import = styles_text.lines().any(|l| l.contains(COLORS_FILE) && l.trim().starts_with("@import"));
            if !has_import {
                let new_text = inject_at_top(
                    &styles_text,
                    MARKER_OPEN,
                    MARKER_CLOSE,
                    &format!("@import \"{}\";", COLORS_FILE),
                );
                ops.push(WriteOp::File {
                    adapter: "yasb", target: styles, content: new_text, atomic: false,
                });
            }
            Ok(ops)
        }
    }

    fn reload(&self) -> Result<ReloadOutcome> {
        if Self::watching_stylesheet() {
            tracing::info!("yasb watcher enabled; skipping yasbc to prevent flicker");
            return Ok(ReloadOutcome { live_reload: 1, ..Default::default() });
        }

        let mut cmd = Command::new("yasbc");
        cmd.creation_flags(0x08000000);
        cmd.arg("reload");

        if let Ok(output) = cmd.output() {
            if output.status.success() {
                tracing::info!("yasb reloaded via yasbc (watcher disabled)");
                return Ok(ReloadOutcome { live_reload: 1, ..Default::default() });
            }
        }

        tracing::warn!("yasbc not found; config written but YASB may need a manual restart");
        Ok(ReloadOutcome { deferred: 1, ..Default::default() })
    }
}